import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import fs from 'fs';
import { GoogleGenAI, ThinkingLevel, Type } from '@google/genai';
import { initializeApp, cert, getApps } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import firebaseConfig from './firebase-applet-config.json' with { type: 'json' };

// Initialize Firebase Admin
if (!getApps().length) {
  initializeApp({
    projectId: firebaseConfig.projectId,
  });
}
const db = getFirestore();

// Initialize Gemini AI SDK
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

async function startServer() {
  const app = express();
  app.use(express.json({ limit: '10mb' }));

  // Ensure assets directory exists
  const assetsDir = path.resolve(__dirname, 'src/assets/images');
  if (!fs.existsSync(assetsDir)) {
    fs.mkdirSync(assetsDir, { recursive: true });
  }

  // --- API Routes ---

  // 1. AI Consultant Chat (gemini-4-hydrogen or gemini-4-neon)
  app.post('/api/chat', async (req, res) => {
    try {
      const { messages } = req.body; // array of { role: 'user' | 'model', content: string }
      if (!messages || !Array.isArray(messages)) {
        return res.status(400).json({ error: 'Messages array is required' });
      }

      const formattedHistory = messages.slice(0, -1).map((m: any) => ({
        role: m.role === 'user' ? 'user' : 'model',
        parts: [{ text: m.content }],
      }));

      const lastMessage = messages[messages.length - 1]?.content || '';

      const chat = ai.chats.create({
        model: 'gemini-4-hydrogen',
        history: formattedHistory,
        config: {
          systemInstruction: `You are the Lead AI Solutions Architect at Innovative AI Solutions in Toronto, Ontario. You help businesses design custom AI agents, machine learning predictive models, and workflow automations. Be professional, highly knowledgeable, practical, and solution-oriented. Answer questions about AI deployment, ROI, data pipelines, and custom agentic workflows with clarity and precision.`,
        },
      });

      const response = await chat.sendMessage({ message: lastMessage });
      res.json({ text: response.text || 'I am ready to help you architect your AI solution.' });
    } catch (error: any) {
      console.error('Chat error:', error);
      res.status(500).json({ error: error.message || 'Failed to generate chat response' });
    }
  });

  // 2. High Thinking AI Project Estimator & ROI Analyzer (gemini-4-carbon with ThinkingLevel.HIGH)
  app.post('/api/estimate', async (req, res) => {
    try {
      const { companyName, industry, currentChallenge, targetOutcome } = req.body;
      const prompt = `Perform a comprehensive AI feasibility and ROI analysis for:
Company: ${companyName || 'Enterprise'}
Industry: ${industry || 'Technology / Operations'}
Current Challenge: ${currentChallenge}
Desired Target Outcome: ${targetOutcome}

Provide:
1. Executive Summary & Recommended AI Agent Architecture
2. Estimated Time to ROI (Weeks/Months)
3. Projected Cost Reduction & Revenue Lift %
4. Step-by-step Implementation Roadmap (4 Stages)
5. Recommended Gemini Model and Data Pipeline requirements`;

      const response = await ai.models.generateContent({
        model: 'gemini-4-carbon',
        contents: prompt,
        config: {
          thinkingConfig: { thinkingLevel: ThinkingLevel.HIGH },
          systemInstruction: 'You are an elite enterprise AI consultant and chief technology strategist.',
        },
      });

      res.json({ analysis: response.text });
    } catch (error: any) {
      console.error('Estimate error:', error);
      res.status(500).json({ error: error.message || 'Failed to generate AI estimate' });
    }
  });

  // 3. High-Quality Image Generation (gemini-3-pro-image-preview / gemini-nano-banana-2.1 with 1K, 2K, 4K support)
  app.post('/api/generate-image', async (req, res) => {
    try {
      const { prompt, resolution = '1K', aspectRatio = '16:9' } = req.body;
      if (!prompt) {
        return res.status(400).json({ error: 'Prompt is required' });
      }

      // We use gemini-3-pro-image-preview for high-quality image generation
      const response = await ai.models.generateImages({
        model: 'gemini-3-pro-image-preview',
        prompt: `${prompt}, cinematic lighting, photorealistic, professional 8k render, resolution ${resolution}`,
        config: {
          numberOfImages: 1,
          outputMimeType: 'image/jpeg',
          aspectRatio: aspectRatio as any,
        },
      });

      const generatedImage = response.generatedImages?.[0];
      if (!generatedImage?.image?.imageBytes) {
        throw new Error('No image generated by model');
      }

      const buffer = Buffer.from(generatedImage.image.imageBytes, 'base64');
      const filename = `ai_asset_${Date.now()}.jpg`;
      const filepath = path.join(assetsDir, filename);
      fs.writeFileSync(filepath, buffer);

      const urlPath = `/src/assets/images/${filename}`;
      res.json({ url: urlPath });
    } catch (error: any) {
      console.error('Image generation error:', error);
      res.status(500).json({ error: error.message || 'Failed to generate image' });
    }
  });

  // 4. Firestore Consultation Bookings API
  app.post('/api/consultations', async (req, res) => {
    try {
      const { name, email, company, service, message } = req.body;
      if (!name || !email || !message) {
        return res.status(400).json({ error: 'Name, email, and message are required' });
      }

      const docRef = await db.collection('consultations').add({
        name,
        email,
        company: company || '',
        service: service || 'General AI',
        message,
        createdAt: new Date().toISOString(),
      });

      res.json({ success: true, id: docRef.id });
    } catch (error: any) {
      console.error('Firestore consultation error:', error);
      res.status(500).json({ error: error.message || 'Failed to save consultation' });
    }
  });

  // --- Vite Middleware in Dev ---
  const vite = await createViteServer({
    server: { middlewareMode: true },
    appType: 'spa',
  });
  app.use(vite.middlewares);

  const port = 3000;
  app.listen(port, '0.0.0.0', () => {
    console.log(`Server running on http://localhost:${port}`);
  });
}

startServer();
